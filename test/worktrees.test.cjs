const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

test('worktree coordinator scopes navigation/actions, safety, challenges and invoking-agent context', async (t) => {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'gittygo-worktrees-')));
  const old = { ...process.env };
  const home = path.join(root, 'home'); await fs.mkdir(home);
  Object.assign(process.env, { HOME: home, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_NOSYSTEM: '1', GITTYGO_STATE_DIR: path.join(home, 'state') });
  const repo = path.join(root, 'repo'); await fs.mkdir(repo);
  const git = (where, ...args) => execFileSync('git', ['-C', where, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git(repo, 'init', '-q'); git(repo, 'config', 'user.name', 'Fixture'); git(repo, 'config', 'user.email', 'fixture@example.invalid');
  await fs.writeFile(path.join(repo, 'file'), 'seed\n'); git(repo, 'add', '.'); git(repo, 'commit', '-qm', 'seed');
  const mainBranch = git(repo, 'branch', '--show-current');
  const linked = path.join(root, 'linked'); git(repo, 'worktree', 'add', '-qb', 'linked', linked);
  const detached = path.join(root, 'detached'); git(repo, 'worktree', 'add', '--detach', detached);
  const { createWorkspaceController } = require('../src/workspace-controller.cjs');
  const { createRpcLedger } = require('../src/rpc-idempotency.cjs');
  const sessions = require('../src/session-store.cjs');
  const controller = await createWorkspaceController(repo);
  t.after(async () => { await controller.close(); await fs.rm(root, { recursive: true, force: true }); for (const key of Object.keys(process.env)) if (!(key in old)) delete process.env[key]; Object.assign(process.env, old); });
  const call = async (method, args = []) => controller.dispatch(method, args);
  const ok = (reply) => { assert.equal(reply.ok, true, JSON.stringify(reply)); return reply.result; };
  const confirm = async (reply, choice = 1) => { assert.equal(reply.ok, true); assert.ok(reply.confirmation); return call('confirm', [reply.confirmation.id, choice]); };
  let entries = ok(await call('worktrees'));
  assert.equal(entries.length, 3); assert.equal(entries.find(e => e.path === detached).detached, true);
  git(repo, 'worktree', 'lock', '--reason', 'fixture locked', detached);
  entries = ok(await call('worktrees')); assert.equal(entries.find(e => e.path === detached).locked, true);
  ok(await call('selectWorktree', [detached])); assert.equal(ok(await call('state')).branch, 'detached');
  const missing = path.join(root, 'missing'); git(repo, 'worktree', 'add', '-qb', 'missing', missing); await fs.rm(missing, { recursive: true });
  const unavailable = ok(await call('worktrees')).find(e => e.path === missing); assert.equal(unavailable.valid, false); assert.equal(unavailable.prunable, true);
  assert.equal((await call('selectWorktree', [missing])).ok, false); assert.equal((await call('removeWorktree', [missing])).ok, false);
  ok(await call('selectWorktree', [linked]));
  assert.equal(ok(await call('state')).repo, linked);
  assert.equal(git(repo, 'branch', '--show-current'), mainBranch);
  await fs.writeFile(path.join(linked, 'file'), 'linked edit\n');
  assert.ok(ok(await call('diff', ['file', 'unstaged'])).patch.includes('linked edit'));
  ok(await call('target', [linked, 'stageFile', ['file']]));
  assert.equal(git(repo, 'diff', '--cached'), ''); assert.ok(git(linked, 'diff', '--cached').includes('linked edit'));
  const context = await sessions.getContext(controller.sessionId);
  assert.equal(context.repo.root, repo);
  assert.equal(context.events.at(-1).payload.targetWorktree, linked);
  assert.deepEqual(context.targetWorktrees, [linked]);
  assert.equal(context.externalStateChanged, false);
  await fs.writeFile(path.join(repo, 'main-only'), 'source edit');
  ok(await call('target', [repo, 'stageFile', ['main-only']]));
  const mixedContext = await sessions.getContext(controller.sessionId);
  assert.equal(mixedContext.events.length, 2, 'staging coalescing must not merge different target worktrees');
  assert.deepEqual(mixedContext.events.map(e => e.payload.targetWorktree), [linked, repo]);
  ok(await call('target', [repo, 'unstageFile', ['main-only']])); await fs.unlink(path.join(repo, 'main-only'));
  // A delayed invocation retains the explicitly captured target even after navigation.
  ok(await call('selectWorktree', [repo]));
  ok(await call('target', [linked, 'commit', ['linked commit', false]]));
  assert.equal(git(linked, 'log', '-1', '--format=%s'), 'linked commit'); assert.equal(git(repo, 'log', '-1', '--format=%s'), 'seed');
  assert.equal((await call('selectWorktree', [home])).ok, false);
  assert.equal((await call('target', [home, 'stageAll', []])).ok, false);
  assert.equal((await call('readTarget', [linked, 'stageAll', []])).ok, false);
  assert.equal(ok(await call('readTarget', [linked, 'history', [10]]))[0].subject, 'linked commit');
  assert.equal((await call('target', [linked, 'readTarget', [repo, 'state', []]])).ok, false);
  assert.match((await call('switchBranch', ['linked'])).error.message, /View worktree/);
  assert.equal(ok(await call('branches')).find(b => b.name === 'linked').worktree, linked);
  for (const target of [repo, detached]) assert.equal((await call('removeWorktree', [target])).ok, false);
  assert.equal((await call('removeWorktree', [linked])).ok, false, 'cached views protect drafts until the window closes');
  const removable = path.join(root, 'removable'); git(repo, 'worktree', 'add', '-qb', 'removable', removable);
  await fs.writeFile(path.join(removable, 'dirty'), 'do not remove');
  assert.equal((await call('removeWorktree', [removable])).ok, false); await fs.unlink(path.join(removable, 'dirty'));
  const staleRemoval = await call('removeWorktree', [removable]); await fs.writeFile(path.join(removable, 'late'), 'changed');
  assert.equal((await confirm(staleRemoval)).ok, false); assert.ok(await fs.stat(removable)); await fs.unlink(path.join(removable, 'late'));
  // A pending removal cannot delete a newly opened native/browser view.
  const selectedRemoval = await call('removeWorktree', [removable]); const other = await createWorkspaceController(removable);
  assert.equal((await confirm(selectedRemoval)).ok, false); await other.close();
  const afterRemovedController = await call('createWorktree', ['after-removal', 'after-removal', true]);
  const removal = await call('removeWorktree', [removable]); ok(await confirm(removal)); assert.equal(await fs.stat(removable).catch(() => null), null);
  assert.equal((await call('confirm', [removal.confirmation.id, 1])).ok, false);
  // Removing any member invalidates an already reviewed family-creation challenge.
  assert.equal((await confirm(afterRemovedController)).ok, false); // family changed, fail fresh rather than wrong-id routing
  const ledger = createRpcLedger();
  const requestId = require('node:crypto').randomUUID();
  const createRequest = { method: 'createWorktree', args: ['created', 'new-branch', true], requestId };
  const replies = await Promise.all([1, 2].map(() => ledger.execute('fixture', createRequest, () => call(createRequest.method, createRequest.args))));
  assert.equal(replies[0], replies[1]);
  const creation = JSON.parse(replies[0]);
  assert.match(creation.confirmation.detail, /Destination:.*created/);
  const creationConfirm = { method: 'confirm', args: [creation.confirmation.id, 1], requestId: require('node:crypto').randomUUID() };
  const results = await Promise.all([1, 2].map(() => ledger.execute('fixture', creationConfirm, () => call('confirm', creationConfirm.args))));
  assert.equal(results[0], results[1]); ok(JSON.parse(results[0]));
  assert.equal(git(path.join(root, 'created'), 'branch', '--show-current'), 'new-branch');
  assert.equal(git(repo, 'branch', '--show-current'), mainBranch);
  const bad = await call('createWorktree', ['../escape', 'escape', true]); assert.equal(bad.ok, false);
  git(repo, 'branch', 'existing'); ok(await confirm(await call('createWorktree', ['existing-folder', 'existing', false])));
  assert.equal(git(path.join(root, 'existing-folder'), 'branch', '--show-current'), 'existing');
  const staleCreate = await call('createWorktree', ['stale', 'stale-branch', true]); git(repo, 'branch', 'external');
  assert.equal((await confirm(staleCreate)).ok, false); assert.equal(await fs.stat(path.join(root, 'stale')).catch(() => null), null);
});

test('non-Git directories are friendly and only explicitly confirmed initialization runs', async (t) => {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'gittygo-nonrepo-')));
  const old = process.env.GITTYGO_STATE_DIR; process.env.GITTYGO_STATE_DIR = path.join(root, 'state');
  const directory = path.join(root, 'folder'); await fs.mkdir(directory); await fs.writeFile(path.join(directory, 'keep'), 'unchanged');
  const { createWorkspaceController } = require('../src/workspace-controller.cjs');
  const c = await createWorkspaceController(directory, { confirmationTtlMs: 10000 });
  t.after(async () => { await c.close(); await fs.rm(root, { recursive: true, force: true }); if (old === undefined) delete process.env.GITTYGO_STATE_DIR; else process.env.GITTYGO_STATE_DIR = old; });
  assert.equal((await c.dispatch('state')).result.nonRepository, true);
  assert.equal(await fs.stat(path.join(directory, '.git')).catch(() => null), null);
  assert.match((await c.dispatch('stageAll')).error.message, /not a Git repository/);
  let reply = await c.dispatch('initializeRepository');
  assert.equal((await c.dispatch('confirm', [reply.confirmation.id, 0])).result.cancelled, true);
  assert.equal(await fs.stat(path.join(directory, '.git')).catch(() => null), null);
  reply = await c.dispatch('initializeRepository'); await fs.writeFile(path.join(directory, 'late'), 'freshness');
  assert.equal((await c.dispatch('confirm', [reply.confirmation.id, 1])).ok, false);
  reply = await c.dispatch('initializeRepository');
  const result = await c.dispatch('confirm', [reply.confirmation.id, 1]); assert.equal(result.ok, true, JSON.stringify(result));
  assert.equal(result.result.initialized, true); assert.equal((await c.dispatch('state')).result.nonRepository, undefined);
  assert.equal(await fs.readFile(path.join(directory, 'keep'), 'utf8'), 'unchanged');
  assert.equal((await c.dispatch('state')).result.staged.length, 0);
});
